"""Adapter for MolmoBot-Data trajectory files (``allenai/molmobot-data``).

Each ``trajectories_batch_<i>_of_<n>.h5`` holds ``traj_<k>`` groups generated by the
MolmoBot planner in MolmoSpaces (MuJoCo) houses on two robots:

* ``franka_droid``: Franka FR3 + Robotiq 2F-85 on a fixed pedestal (``Franka*`` configs);
* ``rby1m``: Rainbow RB-Y1M, holonomic base + 6-DoF torso + two 7-DoF arms with parallel
  grippers (``RBY1*`` and ``DoorOpening`` configs).

What the files contain (verified on every catalogued package, see docs/sources.md):
per-step robot joint state (``obs/agent/qpos``, JSON by move group), commanded actions,
robot base pose, recorded TCP poses, per-step success, task info, and the frozen
generation config (initial poses of all scene objects, task object names, goals).
**Per-step object poses are not stored** (``env_states`` only has the robot). Object
tracks are therefore measured only at ``t = 0`` (``valid[0]``); door handles (from
``door_state``) and the opened joint of open tasks (``task_info.joint_position``) are
measured at every step. :func:`rigid_grasp_track` derives a pick-object track under a
rigid-grasp assumption; it is not part of the episode.

Effector poses come from forward kinematics of the pinned MolmoSpaces robot models
(see ``catalog/molmobot.yaml``), verified per trajectory against the recorded TCP poses
(``provenance["fk_check"]``). The grasp-center frame is measured from the model
geometry with the fingers open, as in the robosuite adapter: origin = midpoint of the
two finger contact faces, +z = palm -> that midpoint (approach), +y = finger-1 face ->
finger-2 face (closing). Nothing is simulated or stepped.
"""
