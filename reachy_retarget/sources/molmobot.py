class RobotFiles:
    """Read-only view of a robot asset tree (directory or zip archive)."""

    def __init__(self, path, subdir: str = ""):
        self.path, self.subdir = Path(path), subdir.strip("/")
        base = self.path / self.subdir if self.subdir else self.path
        if self.path.is_dir():
            self.names = {p.relative_to(base).as_posix() for p in base.rglob("*") if p.is_file()}
            self._zip = None
        else:
            self._zip = zipfile.ZipFile(self.path)
            pre = f"{self.subdir}/" if self.subdir else ""
            self.names = {n[len(pre):] for n in self._zip.namelist() if n.startswith(pre) and not n.endswith("/")}

    def read(self, rel: str) -> bytes | None:
        rel = posixpath.normpath(rel)
        if rel not in self.names:
            return None
        full = f"{self.subdir}/{rel}" if self.subdir else rel
        return self._zip.read(full) if self._zip else (self.path / full).read_bytes()

    def manifest(self) -> dict | None:
        data = self.read("MANIFEST.json")
        return json.loads(data) if data else None


def compile_robot_xml(files: RobotFiles, main: str):
    """Flatten ``<include>``, resolve asset paths and sub-models for ``MjModel.from_xml_string``.

    Returns ``(xml, assets, missing)``. Missing mesh files become 1 mm spheres and
    missing textures are dropped: body/site/joint kinematics stay exact, geometry does not.
    """
    assets, missing = {}, []

    def load(rel):
        data = files.read(rel)
        if data is None:
            raise FileNotFoundError(f"{files.path}: {rel}")
        root = ET.fromstring(data)
        base = posixpath.dirname(rel)
        comp = root.find("compiler")
        dirs = {"mesh": "", "texture": "", "hfield": "", "skin": ""}
        if comp is not None:
            md = comp.attrib.pop("meshdir", "")
            td = comp.attrib.pop("texturedir", "")
            ad = comp.attrib.pop("assetdir", "")
            dirs = {"mesh": md or ad, "texture": td or ad, "hfield": ad, "skin": md or ad}
        _inline(root, base)
        dropped = set()
        for el in root.iter():
            if el.tag in dirs and el.get("file"):
                f = posixpath.normpath(posixpath.join(base, dirs[el.tag], el.get("file")))
                data = files.read(f)
                if data is None:
                    missing.append(f)
                    dropped.add((el.tag, el.get("name") or posixpath.splitext(posixpath.basename(f))[0]))
                    el.set("file", "")
                else:
                    assets[f] = data
                    el.set("file", f)
            elif el.tag == "model" and el.get("file"):
                f = posixpath.normpath(posixpath.join(base, el.get("file")))
                assets[f] = load(f).encode()
                el.set("file", f)
        _placeholders(root, dropped)
        return ET.tostring(root, encoding="unicode")

    def _inline(node, base):
        for i, ch in enumerate(list(node)):
            if ch.tag == "include":
                inc = posixpath.normpath(posixpath.join(base, ch.get("file")))
                data = files.read(inc)
                if data is None:
                    raise FileNotFoundError(f"{files.path}: include {inc}")
                sub = ET.fromstring(data)
                ibase = posixpath.dirname(inc)
                for el in sub.iter():  # paths inside an included file are relative to it
                    if el.tag in ("mesh", "texture", "hfield", "skin") and el.get("file"):
                        el.set("file", posixpath.relpath(posixpath.join(ibase, el.get("file")), base or "."))
                _inline(sub, base)
                pos = list(node).index(ch)
                node.remove(ch)
                for k, s in enumerate(list(sub)):
                    node.insert(pos + k, s)
            else:
                _inline(ch, base)

    def _placeholders(root, dropped):
        if not dropped:
            return
        meshes = {n for t, n in dropped if t == "mesh"}
        textures = {n for t, n in dropped if t == "texture"}
        for parent in root.iter():
            for el in list(parent):
                if el.tag in ("mesh", "texture") and el.get("file") == "":
                    parent.remove(el)
        for mat in root.iter("material"):
            if mat.get("texture") in textures:
                mat.attrib.pop("texture")
        for geom in root.iter("geom"):
            if geom.get("mesh") in meshes:
                geom.attrib.pop("mesh")
                geom.set("type", "sphere")
                geom.set("size", "0.001")

    xml = load(main)
    return xml, assets, missing


class RobotModel:
    """Compiled source robot with FK helpers and gripper geometry measured once."""

    def __init__(self, name: str, files: RobotFiles):
        import mujoco

        spec = ROBOTS[name]
        self.mj, self.name, self.spec, self.files = mujoco, name, spec, files
        self.xml, self.assets, self.missing = compile_robot_xml(files, spec["xml"])
        self.m = mujoco.MjModel.from_xml_string(self.xml, self.assets)
        self.d = mujoco.MjData(self.m)
        p = spec["prefix"]
        jid = lambda n: self.m.joint(p + n).id
        self.groups = {g: self.m.jnt_qposadr[[jid(n) for n in names]] for g, names in spec["groups"].items()}
        self.coupled = {self.m.jnt_qposadr[jid(k)]: self.m.jnt_qposadr[[jid(n) for n in v]]
                        for k, v in spec.get("coupled", {}).items()}
        self._check_coupling()
        self.grippers = {k: _Gripper(self, k, e) for k, e in spec["effectors"].items()}
        self.torso = self.m.body(p + spec["torso_body"]).id if "torso_body" in spec else None
        self.base_link = self.m.body(p + spec["base_link"]).id if "base_link" in spec else None
        self.base_body = self.m.body(p + "base").id if name == "rby1m" else None

    def _check_coupling(self):
        """The closed-chain Robotiq joints follow the driver (connect residual < 1e-5 m)."""
        mj, m, d = self.mj, self.m, self.d
        if not self.coupled:
            return
        for a in (0.2, 0.5, 0.8):
            d.qpos[:] = m.qpos0
            for drv, rest in self.coupled.items():
                d.qpos[drv] = a
                d.qpos[rest] = a
            mj.mj_forward(m, d)
            res = [abs(d.efc_pos[i]) for i in range(d.nefc) if d.efc_type[i] == mj.mjtConstraint.mjCNSTR_EQUALITY]
            if res and max(res) > 1e-5:
                raise ValueError(f"{self.name}: coupled gripper joints violate the closed chain ({max(res):.2e} m)")

    def set_groups(self, q: dict):
        d = self.d
        d.qpos[:] = self.m.qpos0
        for g, adr in self.groups.items():
            vals = q.get(g)
            if vals is None or len(vals) == 0:
                continue
            d.qpos[adr] = vals
        for drv, rest in self.coupled.items():
            d.qpos[rest] = d.qpos[drv]
        self.mj.mj_kinematics(self.m, d)

    def describe(self) -> dict:
        man = self.files.manifest() or {}
        return {"name": self.name, "xml": self.spec["xml"], "files": str(self.files.path),
                "catalog_id": man.get("catalog_id", self.spec["catalog_id"]), "shard_sha256": man.get("shard_sha256"),
                "xml_sha256": hashlib.sha256(self.files.read(self.spec["xml"])).hexdigest(),
                "missing_assets": len(self.missing), "license": self.spec["license"],
                "effectors": {k: g.describe() for k, g in self.grippers.items()}}


class _Gripper:
    """Two-finger gripper; contact faces measured from collision geometry with fingers open."""

    def __init__(self, robot: RobotModel, key: str, spec: dict):
        mj, m, d = robot.mj, robot.m, robot.d
        p = robot.spec["prefix"]
        self.key, self.site = key, m.site(p + spec["site"]).id
        self.side = spec["side"]
        self.tcp_keys = spec["tcp_keys"]
        self.fingers = [m.joint(p + n).id for n in spec["fingers"]]
        self.adr = m.jnt_qposadr[self.fingers]
        self.pad_bodies = [m.body(p + n).id for n in spec["pads"]]
        rng = m.jnt_range[self.fingers]
        # Open/closed limits per finger joint: the limit giving the larger contact-face
        # separation is "open" (measured, not assumed; RB-Y1 fingers open at -0.05/+0.05,
        # Robotiq drivers at 0).
        q = m.qpos0[self.adr].copy()
        for j in range(len(self.fingers)):
            seps = []
            for lim in rng[j]:
                qq = q.copy()
                qq[j] = lim
                seps.append(self._measure(robot, qq)[3])
            q[j] = rng[j][int(np.argmax(seps))]
        self.q_open = q
        self.q_closed = np.array([r[0] if o == r[1] else r[1] for o, r in zip(q, rng)])
        Rs, ps, c_body, sep_open, palm = self._measure(robot, self.q_open, keep=True)
        self.pad_local = c_body                       # contact-face centre in each pad body frame
        p1, p2 = self._pads_world(d)
        mid = (p1 + p2) / 2
        z = Rs.T @ (mid - palm)
        z /= np.linalg.norm(z)
        y = Rs.T @ (p2 - p1)
        y -= z * (y @ z)
        y /= np.linalg.norm(y)
        fix = np.column_stack([np.cross(y, z), y, z])
        snapped = np.round(fix)
        self.raw_fix = fix
        ok = np.abs(fix - snapped).max() < np.sin(np.radians(3)) and abs(np.linalg.det(snapped) - 1) < 1e-9
        self.R_fix = snapped if ok else fix
        self.offset = Rs.T @ (mid - ps)
        self.sep_open = sep_open
        # Width is the physical gap between the contact faces (clipped at 0); at the
        # closed joint limit the faces touch (RB-Y1, 0.2 mm) or overlap (Robotiq, -8.6 mm).
        self.gap_at_closed_limit = self._measure(robot, self.q_closed, axis_site=self.axis_site)[3]
        self.width_max = self.sep_open

    def _pads_world(self, d):
        return [d.xpos[b] + d.xmat[b].reshape(3, 3) @ c for b, c in zip(self.pad_bodies, self.pad_local)]

    def _measure(self, robot, q, keep=False, axis_site=None):
        """Contact-face centres: collision points within 1 mm of the innermost point along the finger axis.

        The finger-1 -> finger-2 axis comes from the finger centroids unless ``axis_site``
        (fixed in the site frame, measured at the open pose) is given.
        """
        mj, m, d = robot.mj, robot.m, robot.d
        robot.set_groups({})
        d.qpos[self.adr] = q
        for drv, rest in robot.coupled.items():
            d.qpos[rest] = d.qpos[drv]
        mj.mj_kinematics(m, d)
        pts = [self._collision_points(robot, b) for b in self.pad_bodies]
        Rs = d.site_xmat[self.site].reshape(3, 3)
        if axis_site is None:
            c1, c2 = pts[0].mean(0), pts[1].mean(0)
            axis = (c2 - c1) / np.linalg.norm(c2 - c1)
        else:
            axis = Rs @ axis_site
        if keep:
            self.axis_site = Rs.T @ axis
        faces = []
        for k, P in enumerate(pts):
            s = P @ axis * (1 if k == 0 else -1)          # larger = closer to the other finger
            faces.append(P[s >= s.max() - 1e-3])
        centres = [(F.min(0) + F.max(0)) / 2 for F in faces]
        sep = (centres[1] - centres[0]) @ axis
        if not keep:
            return None, None, None, sep, None
        body_local = [d.xmat[b].reshape(3, 3).T @ (c - d.xpos[b]) for b, c in zip(self.pad_bodies, centres)]
        palm = d.xpos[m.body_parentid[m.jnt_bodyid[self.fingers[0]]]].copy()
        return d.site_xmat[self.site].reshape(3, 3).copy(), d.site_xpos[self.site].copy(), body_local, sep, palm

    @staticmethod
    def _collision_points(robot, body):
        mj, m, d = robot.mj, robot.m, robot.d
        out = []
        sub = [b for b in range(m.nbody) if _in_subtree(m, b, body)]
        for g in range(m.ngeom):
            if m.geom_bodyid[g] not in sub or not (m.geom_contype[g] or m.geom_conaffinity[g]):
                continue
            R, c = d.geom_xmat[g].reshape(3, 3), d.geom_xpos[g]
            if m.geom_type[g] == mj.mjtGeom.mjGEOM_MESH:
                mid = m.geom_dataid[g]
                v = m.mesh_vert[m.mesh_vertadr[mid]:m.mesh_vertadr[mid] + m.mesh_vertnum[mid]]
            elif m.geom_type[g] == mj.mjtGeom.mjGEOM_BOX:
                v = m.geom_size[g] * np.array([[x, y, z] for x in (-1, 1) for y in (-1, 1) for z in (-1, 1)])
            else:
                continue  # placeholders and primitives without a contact face
            out.append(c + v @ R.T)
        if not out:
            raise ValueError(f"{robot.name}: no collision geometry under finger body {body} (finger meshes missing?)")
        return np.concatenate(out)

    def read(self, d) -> tuple[np.ndarray, float]:
        Rs = d.site_xmat[self.site].reshape(3, 3)
        T = np.eye(4)
        T[:3, :3] = Rs @ self.R_fix
        T[:3, 3] = d.site_xpos[self.site] + Rs @ self.offset
        p1, p2 = self._pads_world(d)
        return T, max(0.0, float((p2 - p1) @ T[:3, 1]))

    def site_pose(self, d) -> np.ndarray:
        T = np.eye(4)
        T[:3, :3] = d.site_xmat[self.site].reshape(3, 3)
        T[:3, 3] = d.site_xpos[self.site]
        return T

    def describe(self) -> dict:
        return {"site_to_contract_rotation": self.R_fix.round(6).tolist(),
                "unsnapped_rotation": self.raw_fix.round(6).tolist(),
                "grasp_center_in_site_frame_m": self.offset.round(6).tolist(),
                "finger_q_open": np.round(self.q_open, 6).tolist(), "finger_q_closed": np.round(self.q_closed, 6).tolist(),
                "width_max_m": round(float(self.width_max), 6),
                "face_gap_at_closed_limit_m": round(float(self.gap_at_closed_limit), 6)}


def _in_subtree(m, b, root):
    while b > 0 and b != root:
        b = m.body_parentid[b]
    return b == root


