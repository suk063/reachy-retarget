def _robot_source(name: str, path: Path, root, robot_assets) -> tuple[str, str]:
    """``(path, subdir)`` of the robot asset tree; a zip may hold ``<name>/`` folders."""
    if robot_assets and name in robot_assets:
        p = Path(robot_assets[name])
        if p.is_file() and zipfile.is_zipfile(p):
            with zipfile.ZipFile(p) as z:
                sub = name if any(n.startswith(f"{name}/") for n in z.namelist()) else ""
            return str(p), sub
        return str(p), ""
    return str(_locate_robot(name, path, root)), ""


def _locate_robot(name: str, path: Path, root) -> Path:
    if root is None:
        root = next((p.parent for p in path.resolve().parents if p.name == "raw"), None)
    spec = ROBOTS[name]
    if root is not None:
        d = Path(root) / "raw" / "molmobot" / "robots" / name / spec["version"]
        if d.exists():
            return d
    raise FileNotFoundError(f"robot assets for {name!r} not found; fetch {spec['catalog_id']} and run "
                            "molmobot_fetch.unpack_robot_assets, or pass robot_assets={name: dir_or_zip}")


