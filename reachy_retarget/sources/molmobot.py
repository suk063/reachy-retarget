class _Stub:
    _qualname = ""

    def __init__(self, *args, **kwargs):
        pass

    def __setstate__(self, state):
        self.__dict__["_state"] = state


class _ConfigUnpickler(pickle.Unpickler):
    """Only numpy array/scalar reconstruction and paths; every other class becomes an inert stub."""

    def find_class(self, module, name):
        if (module, name) in _NUMPY_OK:
            import importlib
            return getattr(importlib.import_module(module), name)
        return type(name, (_Stub,), {"_qualname": f"{module}.{name}"})


def _plain(o):
    if isinstance(o, _Stub):
        st = o.__dict__.get("_state") or {}
        if isinstance(st, tuple):
            st = next((s for s in st if isinstance(s, dict)), {})
        if "__dict__" in st:
            st = st["__dict__"]
        return {"__class__": o._qualname, **{k: _plain(v) for k, v in st.items() if not k.startswith("__pydantic")}}
    if isinstance(o, dict):
        return {str(k): _plain(v) for k, v in o.items()}
    if isinstance(o, (list, tuple)):
        return [_plain(v) for v in o]
    if isinstance(o, np.ndarray):
        return o.tolist()
    if isinstance(o, np.generic):
        return o.item()
    if hasattr(o, "__fspath__"):
        return str(o)
    return o


