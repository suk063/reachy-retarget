def _quat_mat(q):
    w, x, y, z = q
    return np.array([[1 - 2 * (y * y + z * z), 2 * (x * y - w * z), 2 * (x * z + w * y)],
                     [2 * (x * y + w * z), 1 - 2 * (x * x + z * z), 2 * (y * z - w * x)],
                     [2 * (x * z - w * y), 2 * (y * z + w * x), 1 - 2 * (x * x + y * y)]])


def _mat_quat(R):
    import mujoco
    q = np.zeros(4)
    mujoco.mju_mat2Quat(q, np.asarray(R, float).reshape(9))
    return q


def _pose7_T(p):
    T = np.eye(4)
    T[:3, :3] = _quat_mat(np.asarray(p[3:7], float) / np.linalg.norm(p[3:7]))
    T[:3, 3] = p[:3]
    return T


def _rot_angle(Ra, Rb) -> float:
    """Angle of Ra^T Rb, accurate for small angles."""
    E = Ra.T @ Rb
    v = np.array([E[2, 1] - E[1, 2], E[0, 2] - E[2, 0], E[1, 0] - E[0, 1]]) / 2
    return float(np.arctan2(np.linalg.norm(v), (np.trace(E) - 1) / 2))


def _yaw_quat(yaw):
    return np.array([np.cos(yaw / 2), 0.0, 0.0, np.sin(yaw / 2)])


def _t0_track(pose7, T: int, role: str, geometry: dict) -> ObjectTrack:
    pose = np.tile(np.asarray(pose7, float), (T, 1))
    valid = np.zeros(T, bool)
    valid[0] = True
    return ObjectTrack(pose=pose, valid=valid, role=role, geometry={**geometry, "measured_rows": "t0 only"})


# ---------------------------------------------------------------- adapter

def _member_info(path: Path, packages):
    try:
        from .molmobot_fetch import find_package
        return find_package(path, packages)
    except Exception:  # noqa: BLE001 - catalog lookup is optional provenance
        return None, None


def _layout(path: Path):
    """``(config, split, part, house)`` from ``.../<config>/<split>/part<k>/<house>/<file>`` when present."""
    parts = path.resolve().parts
    if len(parts) >= 5 and re.fullmatch(r"part\d+", parts[-3]):
        return parts[-5], parts[-4], int(parts[-3][4:]), parts[-2]
    return None, None, None, path.parent.name


@register("molmobot")
def read_molmobot_h5(path: Path, *, family: str, trajs=None, root=None, robot_assets=None, packages=None):
    """Yield one :class:`SourceEpisode` per ``traj_<k>`` of a MolmoBot trajectory file.

    ``robot_assets`` maps a robot name (``rby1m``/``franka_droid``) to an unpacked asset
    directory or zip; by default ``<root>/raw/molmobot/robots/<name>/<version>`` is used,
    with ``root`` inferred from ``path`` when it lies under a ``raw/`` folder.
    """
    path = Path(path)
    digest = hashlib.sha256(path.read_bytes()).hexdigest()
    pkg, member = _member_info(path, packages)
    config, split, part, house = _layout(path)
    if pkg is not None:
        config, split, part = pkg.config, pkg.split, pkg.part
    batch = re.search(r"batch_(\d+)_of_(\d+)", path.name)
    with h5py.File(path, "r") as f:
        keys = sorted((k for k in f if k.startswith("traj_")), key=lambda k: int(k[5:]))
        if trajs is not None:
            keys = [k for k in keys if k in set(trajs)]
        mask = f["valid_traj_mask"][()].tolist() if "valid_traj_mask" in f else None
        for key in keys:
            yield _episode(f[key], key, path, digest, pkg, member, config, split, part, house, batch, mask,
                           family, root, robot_assets)


def _episode(g, key, path, digest, pkg, member, config, split, part, house, batch, mask, family,
             root, robot_assets):
    scene = json.loads(g["obs_scene"][()].decode())
    cfg = decode_config(scene["frozen_config"])
    rc, tc = cfg["robot_config"], cfg["task_config"]
    rname = rc["name"]
    if rname not in ROBOTS or Path(rc["robot_xml_path"]).name != ROBOTS[rname]["xml"]:
        raise ValueError(f"{path}:{key}: unsupported robot {rname!r} ({rc['robot_xml_path']})")
    robot = _robot(rname, *_robot_source(rname, path, root, robot_assets))
    d = robot.d
    qpos = _json_rows(g["obs/agent/qpos"])
    T = len(qpos)
    extra = g["obs/extra"]
    dt = float(scene["policy_dt_ms"]) / 1000.0
    time = np.arange(T) * dt

    # World frame of the robot's model frame.
    base_pose = np.asarray(extra["robot_base_pose"][()], float)        # (T, 7) x y z wxyz, world
    if rname == "franka_droid":
        h = float((rc.get("base_size") or [0, 0, 0])[2])
        world_from_model = _pose7_T(base_pose[0]) @ _trans(0, 0, h)     # model origin = fr3_link0
    else:
        world_from_model = np.eye(4)                                     # base joints are world x, y, yaw

    poses = {k: np.zeros((T, 4, 4)) for k in robot.grippers}
    widths = {k: np.zeros(T) for k in robot.grippers}
    torso_z = np.zeros(T) if robot.torso is not None else None
    base = np.zeros((T, 3)) if rname == "rby1m" else None
    fk_err = {}
    for t in range(T):
        robot.set_groups(qpos[t])
        for k, gr in robot.grippers.items():
            P, w = gr.read(d)
            poses[k][t], widths[k][t] = world_from_model @ P, w
            # Recorded TCP poses are expressed in the robot base frame on the floor (RB-Y1:
            # x, y, yaw of the base; Franka: the pedestal frame robot_base_pose).
            for tk in gr.tcp_keys:
                if tk in extra and len(extra[tk].shape) == 2:
                    ref = _pose7_T(base_pose[t]) if rname == "franka_droid" else \
                        _trans(*qpos[t]["base"][:2], 0.0) @ _rotz(qpos[t]["base"][2])
                    S = np.linalg.inv(ref) @ world_from_model @ gr.site_pose(d)
                    rec = np.asarray(extra[tk][t], float)
                    e_p = float(np.linalg.norm(S[:3, 3] - rec[:3]))
                    e_r = _rot_angle(S[:3, :3], _quat_mat(rec[3:] / np.linalg.norm(rec[3:])))
                    a = fk_err.setdefault(k, {"key": tk, "pos": [], "rot": []})
                    a["pos"].append(e_p)
                    a["rot"].append(e_r)
                    break
        if torso_z is not None:
            torso_z[t] = (world_from_model @ np.r_[d.xpos[robot.torso], 1.0])[2]
        if base is not None:
            base[t] = qpos[t]["base"][:3]
    if base is not None:
        base[:, 2] = np.unwrap(base[:, 2])
    for k, v in fk_err.items():
        pe, re_ = np.asarray(v.pop("pos")), np.asarray(v.pop("rot"))
        v.update({"pos_median_m": float(np.median(pe)), "pos_p99_m": float(np.percentile(pe, 99)),
                  "pos_max_m": float(pe.max()), "rot_median_rad": float(np.median(re_)),
                  "rot_p99_rad": float(np.percentile(re_, 99)), "rot_max_rad": float(re_.max())})
        # Isolated larger rotation residuals coincide with large joint steps (recording skew
        # between qpos and the TCP observation), so the gate uses the 99th percentile.
        v["ok"] = v["pos_p99_m"] <= FK_TOL_M and v["rot_p99_rad"] <= FK_TOL_RAD

    effectors = {k: Effector(pose=poses[k], width=widths[k],
                             opening=np.clip(widths[k] / robot.grippers[k].width_max, 0.0, 1.0),
                             side_hint=robot.grippers[k].side) for k in robot.grippers}

    task_type = scene.get("task_type")
    objects, articulations, derived_notes = {}, {}, []
    pickup = tc.get("pickup_obj_name")
    if task_type in ("pick", "pick_and_place", "pick_and_place_color", "pick_and_place_next_to") and pickup:
        start = tc.get("pickup_obj_start_pose") or extra["obj_start"][0].tolist()
        objects[pickup] = _t0_track(start, T, "manipulated", {"body": pickup})
        rec_name = tc.get("place_receptacle_name") or scene.get("place_receptacle_name")
        rec_pose = tc.get("place_receptacle_start_pose")
        if rec_name and rec_pose is not None:
            role = ROLE_BY_TASK.get(task_type, {}).get("receptacle", "receptacle")
            objects[rec_name] = _t0_track(rec_pose, T, role, {"body": rec_name})
    task_info = _json_rows(extra["task_info"])
    if task_type == "door_open" and "door_state" in extra:
        ds = _json_rows(extra["door_state"])
        hinge = np.asarray([s["door_position"] for s in ds], float)
        handle = np.asarray([s["handle_position"] for s in ds], float)
        yaw = np.arctan2(handle[:, 1] - hinge[:, 1], handle[:, 0] - hinge[:, 0])
        door = tc.get("door_body_name") or "door"
        articulations[door] = Articulation(joint_names=[f"{door}:hinge"],
                                           qpos=np.asarray([s["joint_angle"][0] for s in ds], float)[:, None])
        objects[f"{door}:handle"] = ObjectTrack(
            pose=np.column_stack([handle, np.stack([_yaw_quat(y) for y in yaw])]), valid=np.ones(T, bool),
            role="manipulated",
            geometry={"body": door, "kind": "door_handle", "handle_extents_m": ds[0].get("handle_extents"),
                      "hinge_position": hinge[0].round(6).tolist(),
                      "orientation": "derived: +x = hinge -> handle direction in the horizontal plane"})
        derived_notes.append("door handle orientation derived from hinge->handle direction")
    elif task_type == "open" and tc.get("joint_name"):
        jp = np.asarray([ti.get("joint_position", np.nan) for ti in task_info], float)
        art = pickup or "articulated_object"
        articulations[art] = Articulation(joint_names=[tc["joint_name"]], qpos=jp[:, None])
        if tc.get("pickup_obj_start_pose") is not None:
            objects[art] = _t0_track(tc["pickup_obj_start_pose"], T, "fixture", {"body": art})

    success_rows = np.asarray(g["success"][()], bool)
    grasp = {}
    for gk in [k for k in extra if k.startswith("grasp_state_")]:
        rows = _json_rows(extra[gk])
        grasp[gk[len("grasp_state_"):]] = {h: {"held": [bool(r[h]["held"]) for r in rows],
                                               "touching": [bool(r[h]["touching"]) for r in rows]} for h in rows[0]}
    traj_idx = int(key[5:])
    valid_traj = None if mask is None or traj_idx >= len(mask) else bool(mask[traj_idx])
    dataset = f"molmobot/{config}/{split}" if config else f"{family}/{path.parent.name}"
    ep_id = "/".join(x for x in (f"part{part}" if part is not None else None, house,
                                 f"batch_{batch.group(1)}_of_{batch.group(2)}" if batch else path.stem, key) if x)
    provenance = {
        "file": str(path), "sha256": digest, "traj_key": key,
        "catalog_package": pkg.id if pkg else None, "package_range_sha256": pkg.range_sha256 if pkg else None,
        "shard": pkg.shard if pkg else None, "shard_sha256": pkg.shard_sha256 if pkg else None,
        "url": pkg.url if pkg else None, "revision": pkg.revision if pkg else None,
        "config": config, "split": split, "part": part, "house": house,
        "scene_family": pkg.scene_family if pkg else None,
        "commercial_valid_episodes": pkg.commercial_valid_episodes if pkg else None,
        "valid_traj": valid_traj, "task_type": task_type, "task_class": cfg.get("task_cls_str"),
        "policy_dt_s": dt, "time_source": "step index * policy_dt_ms (no simulator clock recorded)",
        "robot": robot.describe(), "robot_config": {k: rc.get(k) for k in ("name", "robot_xml_path", "base_size",
                                                                          "default_world_pose", "command_mode")},
        "frame": ("RB-Y1M model frame = world (base joints are world x, y, yaw; robot root 5 mm above the floor)"
                  if rname == "rby1m" else
                  "world_from_fr3_link0 = robot_base_pose * translate(0, 0, base_size[2])"),
        "fk_check": fk_err,
        "torso_height": "world z of link_torso_5 (arm and neck mount)" if torso_z is not None else None,
        "base_yaw": "unwrapped" if base is not None else None,
        "base_hint_source": "robot_base_pose (pedestal frame on the support surface)" if rname == "franka_droid" else None,
        "object_state": ("not recorded per step: object tracks are valid at t0 only (initial pose from the frozen "
                         "config); see rigid_grasp_track for a derived estimate"),
        "derived": derived_notes,
        "pickup_obj_goal_pose": tc.get("pickup_obj_goal_pose"),
        "final_task_info": task_info[-1] if task_info else None,
        "grasp_state": grasp,
        "referral_expressions": scene.get("referral_expressions"),
        "scene_initial_object_poses": tc.get("object_poses"),
        "added_objects": tc.get("added_objects"),
        "success_source": "success[-1] (per-step environment success flag at the final step)",
        "first_success_step": int(np.argmax(success_rows)) if success_rows.any() else None,
        "scene_ref": ("None: the MolmoSpaces house scene (scene_family/house) and its objects are published in "
                      "allenai/molmospaces but are not catalogued or assembled yet"),
    }
    base_hint = None
    if rname == "franka_droid":
        R = _quat_mat(base_pose[0, 3:] / np.linalg.norm(base_pose[0, 3:]))
        base_hint = np.array([base_pose[0, 0], base_pose[0, 1], np.arctan2(R[1, 0], R[0, 0])])
    return SourceEpisode(
        family=family, dataset=dataset, episode_id=ep_id, task=task_type or config or "unknown", time=time,
        effectors=effectors, objects=objects, base=base, base_hint=base_hint, torso_height=torso_z,
        articulations=articulations, scene=None, instruction=scene.get("task_description"),
        success=bool(success_rows[-1]) if len(success_rows) else None,
        regime="mobile_manipulation" if rname == "rby1m" else "tabletop",
        license=(pkg.license if pkg else "ODC-BY-1.0"), provenance=provenance,
        lineage={"generated": False, "synthetic": True, "generator": "MolmoBot planner data generation (MolmoSpaces)",
                 "seed": None})


def _trans(x, y, z):
    T = np.eye(4)
    T[:3, 3] = (x, y, z)
    return T


def _rotz(a):
    T = np.eye(4)
    c, s = np.cos(a), np.sin(a)
    T[:2, :2] = [[c, -s], [s, c]]
    return T


# ---------------------------------------------------------------- derived (not stored)

def rigid_grasp_track(ep: SourceEpisode, obj: str, effector: str | None = None) -> ObjectTrack:
    """Estimate a pick-object track from its t0 pose and the recorded grasp flags.

    Assumptions (a derived label, never stored in episodes): the object rests at its t0
    pose until the first ``held`` or ``touching`` step; during the longest contiguous
    ``held`` run it is rigidly attached to the grasp center with the relative pose of
    the run's first step. Rows between first contact and that run, and after the run,
    are invalid. RB-Y1 files never set ``held`` (verified on the catalogued subset), so
    this only works for the Franka configs.
    """
    track = ep.objects[obj]
    gs = ep.provenance.get("grasp_state", {}).get("pickup_obj", {})
    if not gs:
        raise ValueError("no grasp_state_pickup_obj in this episode")
    key = effector or next(iter(ep.effectors))
    hand = {"gripper": "gripper", "left": "left_gripper", "right": "right_gripper"}[key]
    held = np.asarray(gs[hand]["held"], bool)
    contact = held | np.asarray(gs[hand]["touching"], bool)
    if not held.any():
        raise ValueError(f"{hand} never holds {obj}; held flags are unusable for this episode")
    T = ep.length
    edges = np.flatnonzero(np.diff(np.r_[0, held.astype(int), 0]))
    runs = list(zip(edges[::2], edges[1::2]))
    s, r = max(runs, key=lambda ab: ab[1] - ab[0])
    pose = np.tile(track.pose[0], (T, 1))
    valid = np.zeros(T, bool)
    valid[:int(np.argmax(contact))] = True
    E = ep.effectors[key].pose
    W0 = _pose7_T(track.pose[0])
    if not contact[:s].any():
        valid[:s] = True
    rel = np.linalg.inv(E[s]) @ W0
    for t in range(s, r):
        W = E[t] @ rel
        pose[t] = np.r_[W[:3, 3], _mat_quat(W[:3, :3])]
        valid[t] = True
    return ObjectTrack(pose=pose, valid=valid, role=track.role,
                       geometry={**track.geometry, "derived": "rigid attachment during the longest held run",
                                 "held_rows": [int(s), int(r)]})


